def em_industry_to_board(name: str, boards: list[str]) -> str:
    if not name:
        return ""
    if name in _EM_TO_THS:
        return _EM_TO_THS[name]
    base = name.replace("Ⅱ", "").replace("Ⅲ", "")
    if base in boards:
        return base
    best, score = "", 0
    for b in boards:
        s = len(set(base) & set(b))
        if s > score:
            best, score = b, s
    return best if score >= 2 else base


def zone_of_board(board: str) -> str:
    for z, bs in ZONE_BOARDS.items():
        if board in bs:
            return z
    return "value"
